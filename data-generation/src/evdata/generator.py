"""Synthetic graph-city generator with a known ground truth.

Each city is a spatial graph of nodes. Nodes have observable urban features and
a latent demand. Some nodes receive existing charging stations; their observed
usage is generated by a spatial Huff competition model with measurement noise.

The generator exposes two ground-truth quantities that a real dataset never
would:

* the incremental usage of adding one station at every candidate node,
* the system-wide incremental usage of any portfolio of new stations.

That lets us evaluate placement decisions with real regret, not just a proxy
such as "does a station already exist here?".
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

import networkx as nx
import numpy as np
import pandas as pd
from scipy.spatial import cKDTree

# data-generation/src/evdata/generator.py -> data-generation/
PROJECT_ROOT = Path(__file__).resolve().parents[2]
SYNTHETIC_DIR = PROJECT_ROOT / "data" / "synthetic"


@dataclass
class CityParams:
    seed: int
    split: str
    n_nodes: int
    n_centers: int
    station_rate: float
    ev_base: float
    noise: float
    lambda_norm: float
    shift: bool = False


@dataclass
class SyntheticCity:
    city_id: str
    seed: int
    split: str
    nodes: pd.DataFrame
    edges: np.ndarray
    centers: np.ndarray
    params: dict
    station_nodes: np.ndarray
    station_capacity: np.ndarray
    station_usage: np.ndarray
    latent_demand: np.ndarray
    features: pd.DataFrame = field(default_factory=pd.DataFrame)

    def distance_matrix(self) -> np.ndarray:
        xy = self.nodes[["x", "y"]].to_numpy()
        return np.sqrt(((xy[:, None, :] - xy[None, :, :]) ** 2).sum(axis=2))


def _sigmoid(value):
    return 1.0 / (1.0 + np.exp(-value))


def _normalize(values: np.ndarray) -> np.ndarray:
    values = np.asarray(values, dtype=float)
    lo, hi = np.nanmin(values), np.nanmax(values)
    if hi - lo < 1e-9:
        return np.zeros_like(values)
    return (values - lo) / (hi - lo)


def _make_graph(xy: np.ndarray, k: int = 5) -> nx.Graph:
    tree = cKDTree(xy)
    n = len(xy)
    graph = nx.Graph()
    graph.add_nodes_from(range(n))
    for i in range(n):
        distances, neighbors = tree.query(xy[i], k=min(k + 1, n))
        for distance, j in zip(distances[1:], neighbors[1:]):
            graph.add_edge(i, int(j), weight=float(distance))
    # Connect components with their nearest pair.
    while nx.number_connected_components(graph) > 1:
        components = list(nx.connected_components(graph))
        best = None
        for a in range(len(components)):
            for b in range(a + 1, len(components)):
                candidates = np.array(sorted(components[a]))
                others = np.array(sorted(components[b]))
                d = ((xy[candidates, None, :] - xy[None, others, :]) ** 2).sum(axis=2)
                index = np.unravel_index(np.argmin(d), d.shape)
                distance = float(np.sqrt(d[index]))
                if best is None or distance < best[0]:
                    best = (distance, int(candidates[index[0]]), int(others[index[1]]))
        graph.add_edge(best[1], best[2], weight=best[0])
    return graph


def generate_city(
    seed: int,
    split: str = "train",
    *,
    shift: bool = False,
    n_nodes: int | None = None,
    station_rate: float | None = None,
    ev_base: float | None = None,
    noise_level: float | None = None,
) -> SyntheticCity:
    """Generate one city. Same seed always produces the same city."""
    rng = np.random.default_rng(seed)
    if n_nodes is None:
        n_nodes = int(rng.integers(700, 1800 if not shift else 2400))
    n_centers = int(rng.integers(2, 9))
    if station_rate is None:
        station_rate = float(rng.uniform(0.035, 0.105)) if not shift else float(rng.uniform(0.018, 0.17))
    if ev_base is None:
        ev_base = float(rng.uniform(-0.2, 1.3)) if not shift else float(rng.uniform(-0.9, 1.9))
    if noise_level is None:
        noise_level = float(rng.uniform(0.08, 0.24)) if not shift else float(rng.uniform(0.18, 0.40))
    lambda_norm = float(rng.uniform(0.075, 0.18))

    # Spatial mixture: compact centres, radial corridors, and a low-density
    # background. This produces more realistic polycentric cities than a single
    # Gaussian blob.
    centers = rng.uniform(0.10, 0.90, size=(n_centers, 2))
    angles = rng.uniform(0, 2 * np.pi, size=n_centers)
    assignment = rng.integers(0, n_centers, size=n_nodes)
    xy = centers[assignment] + rng.normal(0, 0.085, size=(n_nodes, 2))
    corridor = rng.random(n_nodes) < 0.24
    if corridor.any():
        t = rng.uniform(0.1, 1.0, size=corridor.sum())
        xy[corridor] = centers[0] + np.column_stack([np.cos(angles[0]) * t, np.sin(angles[0]) * t]) + rng.normal(0, 0.025, size=(corridor.sum(), 2))
    background = rng.random(n_nodes) < 0.16
    xy[background] = rng.uniform(0, 1, size=(background.sum(), 2))
    xy = np.clip(xy, 0.01, 0.99)
    graph = _make_graph(xy, k=6)
    closeness = nx.closeness_centrality(graph)
    closeness = np.array([closeness[i] for i in range(n_nodes)])
    degree = np.array([graph.degree(i) for i in range(n_nodes)], dtype=float)

    # Observable urban form. Zones are soft land-use shares.
    center_dist = np.min(np.sqrt(((xy[:, None, :] - centers[None, :, :]) ** 2).sum(axis=2)), axis=1)
    center_prox = np.exp(-(center_dist**2) / (2 * 0.15**2))
    pop = _normalize(center_prox + 0.18 * rng.normal(size=n_nodes))
    business_raw = 2.4 * center_prox + 0.7 * _normalize(closeness) + 0.4 * rng.random(n_nodes)
    residential_raw = 1.8 * (1 - center_prox) + 0.5 * rng.random(n_nodes)
    industrial_raw = 1.4 * (1 - center_prox) + 0.4 * rng.random(n_nodes)
    zone_matrix = np.column_stack([business_raw, residential_raw, industrial_raw])
    zone_matrix = np.exp(zone_matrix - zone_matrix.max(axis=1, keepdims=True))
    zone_matrix = zone_matrix / zone_matrix.sum(axis=1, keepdims=True)
    zone_business, zone_residential, zone_industrial = zone_matrix.T
    activity = np.clip(
        0.38 * pop + 0.26 * center_prox + 0.18 * zone_business + 0.10 * _normalize(closeness) + 0.08 * rng.random(n_nodes),
        0,
        1,
    )
    income = np.clip(0.28 + 0.44 * center_prox + 0.18 * zone_business + 0.10 * rng.random(n_nodes), 0, 1)
    ev = _sigmoid(2.1 * income - 0.8 + ev_base + 0.38 * rng.normal(size=n_nodes))
    road = np.clip(0.28 + 0.38 * _normalize(closeness) + 0.20 * zone_business + 0.14 * rng.random(n_nodes), 0, 1)
    transit = np.clip(0.25 + 0.45 * _normalize(closeness) + 0.20 * center_prox + 0.10 * rng.random(n_nodes), 0, 1)
    highway = np.clip(0.20 + 0.50 * _normalize(closeness) + 0.20 * zone_industrial + 0.10 * rng.random(n_nodes), 0, 1)
    poi_density = np.clip(0.35 * activity + 0.30 * zone_business + 0.20 * transit + 0.15 * rng.random(n_nodes), 0, 1)
    parking = np.clip(0.30 * activity + 0.25 * road + 0.15 * zone_business + 0.10 * rng.random(n_nodes), 0, 1)
    centrality = _normalize(closeness)

    # Latent demand: polycentric, zone-aware, with spatial shocks that the
    # model can only see through observable proxies.
    shocks = np.zeros(n_nodes)
    for _ in range(max(2, n_centers)):
        shock_center = rng.uniform(0.05, 0.95, size=2)
        shocks += rng.uniform(0.4, 1.6) * np.exp(-((xy - shock_center) ** 2).sum(axis=1) / (2 * 0.09**2))
    latent = (
        120.0
        * (0.25 + pop) ** 0.90
        * (0.30 + activity) ** 0.70
        * (0.35 + ev) ** 0.80
        * (0.40 + centrality) ** 0.50
        * (0.45 + road) ** 0.30
        * (0.55 + 0.9 * zone_business + 0.5 * zone_residential + 0.3 * zone_industrial)
        * (0.55 + 0.45 * transit)
        * (0.60 + 0.40 * highway)
        * (1.0 + 0.18 * _normalize(shocks))
        * np.exp(rng.normal(0, 0.14, size=n_nodes))
    )
    latent = latent / latent.mean() * 100.0

    n_stations = max(5, int(round(n_nodes * station_rate)))
    weights = (latent**1.15) * (0.35 + road) * (0.45 + parking) * (0.5 + zone_business)
    weights = weights / weights.sum()
    station_nodes = rng.choice(n_nodes, size=min(n_stations, n_nodes - 2), replace=False, p=weights)
    capacity = np.clip(rng.lognormal(0.0, 0.30, size=len(station_nodes)), 0.5, 2.6)
    usage = simulate_usage(
        latent[station_nodes],
        capacity,
        _distance_subset(xy, station_nodes),
        lambda_norm,
        rng,
        noise_level,
    )

    nodes = pd.DataFrame(
        {
            "city_id": f"{split}_{seed}",
            "node_id": np.arange(n_nodes),
            "x": xy[:, 0],
            "y": xy[:, 1],
            "population": pop,
            "activity": activity,
            "income": income,
            "ev_adoption": ev,
            "centrality": centrality,
            "road_capacity": road,
            "transit_access": transit,
            "highway_access": highway,
            "parking": parking,
            "poi_density": poi_density,
            "dist_center": center_dist,
            "degree": degree,
            "closeness": closeness,
            "zone_business": zone_business,
            "zone_residential": zone_residential,
            "zone_industrial": zone_industrial,
            "latent_demand": latent,
        }
    )
    station_mask = np.zeros(n_nodes, dtype=int)
    station_mask[station_nodes] = 1
    nodes["is_station"] = station_mask
    nodes["station_capacity"] = 0.0
    nodes.loc[station_nodes, "station_capacity"] = capacity
    nodes["observed_usage"] = np.nan
    nodes.loc[station_nodes, "observed_usage"] = usage

    # Features that an agent could observe before making a decision. Existing
    # station supply is included for usage prediction, but the placement layer
    # recomputes neighbourhood competition when scoring candidates.
    features = nodes.copy()
    features["competing_capacity"] = _competing_capacity(
        xy, station_nodes, capacity, lambda_norm, exclude_self=True
    )
    features["n_stations_1km"] = _count_within(xy, station_nodes, 0.12, exclude_self=True)
    features["nearest_station_dist"] = _nearest_distance(xy, station_nodes, exclude_self=True)
    features["local_population"] = _local_population(xy, pop, 0.20)
    features["local_activity"] = _local_population(xy, activity, 0.20)
    features["city_nodes"] = n_nodes
    features["city_station_rate"] = station_rate
    # For candidates the planned capacity is one connector-equivalent.
    features["planned_capacity"] = np.where(features["is_station"] == 1, features["station_capacity"], 1.0)

    params = CityParams(
        seed=seed,
        split=split,
        n_nodes=n_nodes,
        n_centers=n_centers,
        station_rate=station_rate,
        ev_base=ev_base,
        noise=noise_level,
        lambda_norm=lambda_norm,
        shift=shift,
    )
    return SyntheticCity(
        city_id=f"{split}_{seed}",
        seed=seed,
        split=split,
        nodes=nodes,
        edges=np.array(list(graph.edges()), dtype=int),
        centers=centers,
        params=asdict(params),
        station_nodes=station_nodes,
        station_capacity=capacity,
        station_usage=usage,
        latent_demand=latent,
        features=features,
    )


def _distance_subset(xy: np.ndarray, indices: np.ndarray) -> np.ndarray:
    points = xy[indices]
    return np.sqrt(((points[:, None, :] - points[None, :, :]) ** 2).sum(axis=2))


def simulate_usage(
    demand: np.ndarray,
    capacity: np.ndarray,
    distances: np.ndarray,
    lambda_norm: float,
    rng: np.random.Generator | None = None,
    noise: float = 0.0,
) -> np.ndarray:
    """Huff-style usage: demand is split by capacity and spatial competition."""
    kernel = np.exp(-distances / lambda_norm)
    np.fill_diagonal(kernel, 1.0)
    competition = kernel @ capacity - capacity
    share = capacity / (capacity + competition + 1e-9)
    usage = demand * share
    if rng is not None and noise > 0:
        usage = usage * rng.lognormal(0.0, noise, size=len(usage))
    return np.clip(usage, 0.01, None)


def _competing_capacity(xy, station_nodes, capacity, lambda_norm, exclude_self=False):
    if len(station_nodes) == 0:
        return np.zeros(len(xy))
    d = np.sqrt(((xy[:, None, :] - xy[station_nodes][None, :, :]) ** 2).sum(axis=2))
    kernel = np.exp(-d / lambda_norm)
    competing = kernel @ capacity
    if exclude_self:
        competing[station_nodes] -= capacity
    return competing


def _count_within(xy, station_nodes, radius, exclude_self=False):
    if len(station_nodes) == 0:
        return np.zeros(len(xy))
    d = np.sqrt(((xy[:, None, :] - xy[station_nodes][None, :, :]) ** 2).sum(axis=2))
    counts = (d <= radius).sum(axis=1).astype(float)
    if exclude_self:
        counts[station_nodes] -= 1.0
    return np.clip(counts, 0, None)


def _nearest_distance(xy, station_nodes, exclude_self=False):
    if len(station_nodes) == 0:
        return np.full(len(xy), 1.0)
    d = np.sqrt(((xy[:, None, :] - xy[station_nodes][None, :, :]) ** 2).sum(axis=2))
    if exclude_self:
        d[station_nodes, np.arange(len(station_nodes))] = np.inf
    nearest = d.min(axis=1)
    return np.where(np.isfinite(nearest), nearest, 1.0)


def _local_population(xy, pop, radius):
    d = np.sqrt(((xy[:, None, :] - xy[None, :, :]) ** 2).sum(axis=2))
    kernel = np.exp(-d / radius)
    np.fill_diagonal(kernel, 1.0)
    return kernel @ pop


def total_expected_usage(city: SyntheticCity, station_nodes=None, capacity=None) -> float:
    """Ground-truth total usage for a station set, without measurement noise."""
    if station_nodes is None:
        station_nodes = city.station_nodes
    if capacity is None:
        capacity = city.station_capacity
    station_nodes = np.asarray(station_nodes, dtype=int)
    capacity = np.asarray(capacity, dtype=float)
    if len(station_nodes) == 0:
        return 0.0
    xy = city.nodes[["x", "y"]].to_numpy()[station_nodes]
    distances = np.sqrt(((xy[:, None, :] - xy[None, :, :]) ** 2).sum(axis=2))
    usage = simulate_usage(city.latent_demand[station_nodes], capacity, distances, city.params["lambda_norm"])
    return float(usage.sum())


def candidate_uplift(city: SyntheticCity, candidates: np.ndarray | None = None) -> pd.DataFrame:
    """True incremental system usage if exactly one station is added at a node."""
    if candidates is None:
        candidates = np.where(city.nodes["is_station"].to_numpy() == 0)[0]
    base = total_expected_usage(city)
    rows = []
    existing_nodes = city.station_nodes
    existing_cap = city.station_capacity
    for node in candidates:
        nodes = np.append(existing_nodes, node)
        cap = np.append(existing_cap, 1.0)
        total = total_expected_usage(city, nodes, cap)
        rows.append(
            {
                "city_id": city.city_id,
                "node_id": int(node),
                "uplift": max(0.0, total - base),
                "total_with_site": total,
            }
        )
    return pd.DataFrame(rows)


def make_params(seed: int, split: str, index: int, shift: bool = False) -> dict:
    return {"seed": seed + index, "split": split, "shift": shift}


def generate_batch(
    split: str,
    n_cities: int,
    base_seed: int,
    shift: bool = False,
) -> list[SyntheticCity]:
    cities = []
    for index in range(n_cities):
        city = generate_city(base_seed + index, split=split, shift=shift)
        cities.append(city)
    return cities


def build_benchmark(
    n_train: int = 300,
    n_val: int = 40,
    n_test: int = 40,
    base_seed: int = 202600,
    out_dir: Path = SYNTHETIC_DIR,
) -> dict:
    """Generate three independent city batches and persist them."""
    out_dir.mkdir(parents=True, exist_ok=True)
    train = generate_batch("train", n_train, base_seed)
    val = generate_batch("validation", n_val, base_seed + 1000)
    test = generate_batch("test", n_test, base_seed + 2000)
    shift = generate_batch("test_shift", 20, base_seed + 3000, shift=True)
    all_cities = {city.city_id: city for city in train + val + test + shift}
    import joblib

    joblib.dump(all_cities, out_dir / "cities.joblib")
    summary = {
        "n_train": len(train),
        "n_validation": len(val),
        "n_test": len(test),
        "n_test_shift": len(shift),
        "n_nodes_total": int(sum(len(city.nodes) for city in all_cities.values())),
        "n_stations_total": int(sum(len(city.station_nodes) for city in all_cities.values())),
        "generator_version": "1.0",
        "base_seed": base_seed,
    }
    (out_dir / "benchmark.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return {"cities": all_cities, "summary": summary, "train": train, "val": val, "test": test, "shift": shift}
